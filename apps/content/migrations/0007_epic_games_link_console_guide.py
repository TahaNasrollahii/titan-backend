def create_epic_console_link_guide(apps, schema_editor):
    Guide = apps.get_model("content", "Guide")
    GuideFaq = apps.get_model("content", "GuideFaq")
    Game = apps.get_model("catalog", "Game")

    slug, category, game_slug, title, summary, body, faqs = EPIC_CONSOLE_LINK_GUIDE
    game = Game.objects.filter(slug=game_slug).first() if game_slug else None

    guide, _ = Guide.objects.update_or_create(
        slug=slug,
        defaults={
            "title": title,
            "category": category,
            "game": game,
            "summary": summary,
            "body": body,
            "meta_title": "آموزش اتصال اکانت اپیک گیمز به پلی استیشن یا ایکس باکس | تایتان",
            "meta_description": "آموزش تصویری اتصال (Link) اکانت اپیک گیمز به پلی‌استیشن (PSN) و ایکس‌باکس در ۵ مرحله به همراه نکات محدودیت ۱ ساله تغییر اکانت.",
            "is_published": True,
            "sort_order": 10,
        },
    )
    guide.faqs.all().delete()
    GuideFaq.objects.bulk_create(
        GuideFaq(guide=guide, question=question, answer=answer, sort_order=index)
        for index, (question, answer) in enumerate(faqs)
    )


