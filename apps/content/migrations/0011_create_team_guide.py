def create_team_guide(apps, schema_editor):
    Guide = apps.get_model("content", "Guide")
    GuideFaq = apps.get_model("content", "GuideFaq")
    Game = apps.get_model("catalog", "Game")

    slug, category, game_slug, title, summary, body, faqs = CREATE_TEAM_GUIDE
    game = Game.objects.filter(slug=game_slug).first() if game_slug else None

    guide, _ = Guide.objects.update_or_create(
        slug=slug,
        defaults={
            "title": title,
            "category": category,
            "game": game,
            "summary": summary,
            "body": body,
            "meta_title": "آموزش تصویری ساخت تیم در تایتان و دعوت هم‌تیمی‌ها | تایتان",
            "meta_description": "آموزش گام‌به‌گام و تصویری ساخت تیم در تایتان در ۲ مرحله ساده: ورود به بخش تیم‌های من در پنل کاربری، آپلود لوگو، انتخاب نام تیم و دریافت لینک دعوت هم‌تیمی‌ها.",
            "is_published": True,
            "sort_order": 14,
        },
    )
    guide.faqs.all().delete()
    GuideFaq.objects.bulk_create(
        GuideFaq(guide=guide, question=question, answer=answer, sort_order=index)
        for index, (question, answer) in enumerate(faqs)
    )


