def create_epic_games_change_region_guide(apps, schema_editor):
    Guide = apps.get_model("content", "Guide")
    GuideFaq = apps.get_model("content", "GuideFaq")
    Game = apps.get_model("catalog", "Game")

    slug, category, game_slug, title, summary, body, faqs = EPIC_GAMES_CHANGE_REGION_GUIDE
    game = Game.objects.filter(slug=game_slug).first() if game_slug else None

    guide, _ = Guide.objects.update_or_create(
        slug=slug,
        defaults={
            "title": title,
            "category": category,
            "game": game,
            "summary": summary,
            "body": body,
            "meta_title": "آموزش تصویری تغییر ریجن اکانت اپیک گیمز (فورتنایت) | تایتان",
            "meta_description": "آموزش گام‌به‌گام و تصویری تغییر ریجن اکانت اپیک گیمز برای فورتنایت از طریق تنظیمات حساب (Account Settings) به همراه نکته مهم اتصال به VPN کشور مقصد.",
            "is_published": True,
            "sort_order": 12,
        },
    )
    guide.faqs.all().delete()
    GuideFaq.objects.bulk_create(
        GuideFaq(guide=guide, question=question, answer=answer, sort_order=index)
        for index, (question, answer) in enumerate(faqs)
    )


