def apply_product_seo(apps, schema_editor):
    Product = apps.get_model("catalog", "Product")
    for product in Product.objects.select_related("game", "category").all():
        seo = PRODUCT_SEO_DATA.get(product.slug)
        specs = dict(product.specs or {})

        if seo:
            if seo.get("title") and product.slug == "valorant-point-8900" and product.title.startswith("825"):
                product.title = seo["title"]
            product.subtitle = seo["subtitle"]
            product.description = seo["description"]
            product.tags = seo["tags"]
            product.meta_title = seo["meta_title"]
            product.meta_description = seo["meta_description"]
            product.image_alt = seo["image_alt"]
            specs["keywords"] = "، ".join(seo["keywords"])
            product.specs = specs
            product.save()
        else:
            title = product.title.strip()
            game_title = product.game.title if product.game else ""
            game_en = product.game.title_en if product.game else ""
            cat_name = product.category.name if product.category else "محصولات گیمینگ"
            existing_desc = (product.description or "").strip()

            if "## " not in existing_desc and "چیست؟" not in existing_desc:
                intro = (
                    existing_desc
                    or f"{title} یکی از محبوب‌ترین محصولات بخش {cat_name} در فروشگاه تایتان است که با تضمین اصالت و تحویل سریع عرضه می‌شود."
                )
                game_phrase = f" مرتبط با {game_title} ({game_en})" if game_title else f" در دسته {cat_name}"
                product.description = (
                    f"{intro}\n\n"
                    f"## {title} چیست؟\n"
                    f"{title} از محصولات اورجینال و رسمی{game_phrase} است که به گیمرها امکان می‌دهد تجربه کامل‌تر و بدون محدودیتی داشته باشند.\n\n"
                    f"## مزایا و ویژگی‌های خرید {title}\n"
                    f"- اصالت ۱۰۰٪ تضمین‌شده و تهیه از مسیرهای رسمی و قانونی\n"
                    f"- تحویل سریع مطابق زمان‌بندی اعلام‌شده در مشخصات محصول\n"
                    f"- قیمت رقابتی و پشتیبانی ۲۴ ساعته کارشناسان تایتان"
                )
            keywords = [title, f"خرید {title}", f"قیمت {title}"]
            if game_title:
                keywords.extend([game_title, f"خرید آیتم {game_title}"])
            if game_en:
                keywords.append(game_en)
            if not specs.get("keywords"):
                specs["keywords"] = "، ".join(dict.fromkeys(keywords))
                product.specs = specs
            if not product.meta_title:
                product.meta_title = f"خرید {title} با بهترین قیمت و تحویل فوری | فروشگاه تایتان"[:250]
            if not product.meta_description:
                product.meta_description = (
                    f"خرید {title} با بهترین قیمت، تضمین اصالت ۱۰۰٪ قانونی، تحویل سریع و پشتیبانی ۲۴ ساعته در فروشگاه تایتان."
                )[:490]
            if not product.image_alt:
                product.image_alt = f"خرید {title} از فروشگاه تایتان"[:250]
            product.save()


